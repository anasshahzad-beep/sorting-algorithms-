import time

# 1. Selection Sort
def selection_sort(arr):
    n = len(arr)
    comparisons = 0
    swaps = 0
    for i in range(n - 1):
        min_idx = i
        for j in range(i + 1, n):
            comparisons += 1
            if arr[j] < arr[min_idx]:
                min_idx = j
        if min_idx != i:
            arr[i], arr[min_idx] = arr[min_idx], arr[i]
            swaps += 1
    return comparisons, swaps


# 2. Bubble Sort
def bubble_sort(arr):
    n = len(arr)
    comparisons = 0
    swaps = 0
    for i in range(n - 1):
        swapped = False
        for j in range(n - i - 1):
            comparisons += 1
            if arr[j] > arr[j + 1]:
                arr[j], arr[j + 1] = arr[j + 1], arr[j]
                swaps += 1
                swapped = True
        if not swapped:
            break
    return comparisons, swaps


# 3. Quick Sort
comparisons_qs = 0
swaps_qs = 0

def partition(arr, low, high):
    global comparisons_qs, swaps_qs
    pivot = arr[high]
    i = low - 1

    for j in range(low, high):
        comparisons_qs += 1
        if arr[j] <= pivot:
            i += 1
            arr[i], arr[j] = arr[j], arr[i]
            swaps_qs += 1

    arr[i + 1], arr[high] = arr[high], arr[i + 1]
    swaps_qs += 1
    return i + 1

def quick_sort_helper(arr, low, high):
    if low < high:
        pi = partition(arr, low, high)
        quick_sort_helper(arr, low, pi - 1)
        quick_sort_helper(arr, pi + 1, high)

def quick_sort(arr):
    global comparisons_qs, swaps_qs
    comparisons_qs = 0
    swaps_qs = 0
    quick_sort_helper(arr, 0, len(arr) - 1)
    return comparisons_qs, swaps_qs


