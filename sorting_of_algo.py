comparisons_ms = 0
copies_ms = 0

def merge_sort_helper(arr):
    global comparisons_ms, copies_ms
    if len(arr) > 1:
        mid = len(arr) // 2
        left = arr[:mid]
        right = arr[mid:]

        merge_sort_helper(left)
        merge_sort_helper(right)

        i = j = k = 0
        while i < len(left) and j < len(right):
            comparisons_ms += 1
            if left[i] <= right[j]:
                arr[k] = left[i]
                i += 1
            else:
                arr[k] = right[j]
                j += 1
            copies_ms += 1
            k += 1

        while i < len(left):
            arr[k] = left[i]
            i += 1
            k += 1
            copies_ms += 1

        while j < len(right):
            arr[k] = right[j]
            j += 1
            k += 1
            copies_ms += 1

def merge_sort(arr):
    global comparisons_ms, copies_ms
    comparisons_ms = 0
    copies_ms = 0
    merge_sort_helper(arr)
    return comparisons_ms, copies_ms


