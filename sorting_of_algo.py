def run_test(algo_name, sort_func):
    cases = [
        ("Size 5 - Sorted", [1, 2, 3, 4, 5]),
        ("Size 5 - Reverse Sorted", [5, 4, 3, 2, 1]),
        ("Size 100 - Sorted", list(range(1, 101))),
        ("Size 100 - Reverse Sorted", list(range(100, 0, -1)))
    ]

    print(f"\n=== {algo_name} ===")
    for case_name, original_arr in cases:
        total_time = 0
        comps = 0
        swaps = 0

        for _ in range(3):
            temp_arr = original_arr.copy()
            start = time.time()
            comps, swaps = sort_func(temp_arr)
            end = time.time()
            total_time += (end - start) * 1000000  # microseconds

        avg_time = total_time / 3
        print(f"{case_name}: Avg Time = {avg_time:.2f} us | Comparisons = {comps} | Swaps/Copies = {swaps}")


